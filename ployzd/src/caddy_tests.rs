#[tokio::test]
async fn reconcile_writes_material_and_pins_it_before_load() {
    let directory =
        std::env::temp_dir().join(format!("ployz-caddy-cert-test-{}", std::process::id()));
    let path = directory.join(CONFIG_FILE);
    std::fs::create_dir_all(&directory).unwrap();
    let machine = Machine {
        id: MachineId::parse("a".repeat(32)).unwrap(),
        name: MachineName::parse("node-a").unwrap(),
        subnet: "10.210.1.0/24".parse().unwrap(),
        management_address: ManagementAddress("fdcc::1".parse().unwrap()),
        public_key: WireGuardPublicKey([1; 32]),
        public_ip: None,
        advertised_endpoints: vec![AdvertisedEndpoint("192.0.2.1:51000".parse().unwrap())],
        runtime: Default::default(),
    };
    let observations = [observation(
        1,
        &machine.id,
        "api",
        Some([10, 210, 1, 2]),
        vec![ingress("secure.example.com", 8443, HttpProtocol::Https)],
    )];
    let certificates = BTreeMap::from([(
        IngressHost::parse("secure.example.com").unwrap(),
        CertificateRow::from_parts(CertificateMaterial::new("CERT-BODY", "KEY-BODY"), None),
    )]);
    let admin = FakeAdmin::default();
    let certs = directory.join("certs");
    std::fs::create_dir_all(&certs).unwrap();
    let stale_cert = certs.join("secure.example.com-old.crt");
    let stale_key = certs.join("secure.example.com-old.key");
    std::fs::write(&stale_cert, "OLD").unwrap();
    std::fs::write(&stale_key, "OLD").unwrap();

    reconcile(&machine, &observations, &certificates, &path, Some(&admin))
        .await
        .unwrap();

    let caddyfile = std::fs::read_to_string(&path).unwrap();
    let pin = pinned_tls_line(&caddyfile, "secure.example.com").expect("https pin");
    let (cert_name, key_name) = pinned_file_names(pin);
    let cert = certs.join(&cert_name);
    let key = certs.join(&key_name);
    assert_eq!(std::fs::read_to_string(&cert).unwrap(), "CERT-BODY");
    assert_eq!(std::fs::read_to_string(&key).unwrap(), "KEY-BODY");
    assert_eq!(
        std::fs::metadata(&key).unwrap().permissions().mode() & 0o777,
        0o600
    );
    assert!(!stale_cert.exists());
    assert!(!stale_key.exists());
    let adapted = admin.adapted.lock().unwrap();
    assert!(
        adapted
            .last()
            .is_some_and(|config| config.contains(&format!("tls /config/certs/{cert_name}")))
    );
    std::fs::remove_dir_all(directory).unwrap();
}

fn pinned_tls_line<'a>(caddyfile: &'a str, hostname: &str) -> Option<&'a str> {
    let needle = format!("tls /config/certs/{hostname}-");
    caddyfile.lines().find(|line| line.contains(&needle))
}

fn pinned_file_names(pin: &str) -> (String, String) {
    let mut paths = pin.split_whitespace().skip(1);
    let cert = paths.next().expect("cert path");
    let key = paths.next().expect("key path");
    (
        Path::new(cert)
            .file_name()
            .unwrap()
            .to_str()
            .unwrap()
            .to_owned(),
        Path::new(key)
            .file_name()
            .unwrap()
            .to_str()
            .unwrap()
            .to_owned(),
    )
}

#[derive(Default)]
struct FakeAdmin {
    adapted: Mutex<Vec<String>>,
    fail_load: bool,
}

impl CaddyAdmin for FakeAdmin {
    async fn adapt(&self, caddyfile: &str) -> Result<String, Error> {
        self.adapted.lock().unwrap().push(caddyfile.into());
        if caddyfile.contains("# invalid") {
            Err(Error::Admin("invalid config detected".into()))
        } else {
            Ok("{}".into())
        }
    }

    async fn load(&self, _json: &str) -> Result<(), Error> {
        if self.fail_load {
            Err(Error::Admin("load failed".into()))
        } else {
            Ok(())
        }
    }
}

fn ingress(hostname: &str, port: u16, http_protocol: HttpProtocol) -> PortPublication {
    PortPublication::Ingress {
        hostname: IngressHostname::explicit(hostname).unwrap(),
        load_balancer_port: port.try_into().unwrap(),
        container_port: port.try_into().unwrap(),
        http_protocol,
    }
}

fn reserved(mut observation: ContainerObservation) -> ContainerObservation {
    observation.project_name = ployz_core::ProjectName::system();
    observation
}

fn observation(
    suffix: u8,
    machine_id: &MachineId,
    service_name: &str,
    address: Option<[u8; 4]>,
    ports: Vec<PortPublication>,
) -> ContainerObservation {
    let service_id = ServiceId::parse(format!("{suffix:x}").repeat(32)).unwrap();
    let service_name = ServiceName::parse(service_name).unwrap();
    let resolved_spec: ResolvedServiceSpec = serde_json::from_value(json!({
        "service_id": service_id,
        "name": service_name,
        "mode": { "mode": "replicated", "replicas": 1 },
        "container": { "image": "example.test/image", "pull_policy": "missing" },
        "ports": ports,
    }))
    .unwrap();
    ContainerObservation {
        container_id: ContainerId::parse(format!("{suffix:x}").repeat(64)).unwrap(),
        display_name: format!("{service_name}-{suffix}"),
        created_at_unix_nanos: 0,
        machine_id: *machine_id,
        project_name: ployz_core::ProjectName::parse("app").unwrap(),
        service_id,
        service_name,
        kind: ContainerKind::ServiceContainer,
        runtime: ContainerRuntimeObservation::Running {
            health: HealthObservation::Healthy,
        },
        effective_healthcheck: None,
        resolved_spec,
        address: address.map(|address| ContainerAddress(address.into())),
        labels: BTreeMap::new(),
    }
}

fn custom_observation(
    suffix: u8,
    created_at_unix_nanos: i64,
    machine_id: &MachineId,
    service_name: &str,
    caddy_config: &str,
    address: [u8; 4],
) -> ContainerObservation {
    let mut observation = observation(suffix, machine_id, service_name, Some(address), Vec::new());
    observation.created_at_unix_nanos = created_at_unix_nanos;
    observation.resolved_spec.caddy_config = Some(caddy_config.into());
    observation
}
