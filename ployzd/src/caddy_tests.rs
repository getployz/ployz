#[test]
fn https_site_with_material_pins_tls_paths() {
    let local = MachineId::parse("a".repeat(32)).unwrap();
    let observations = vec![observation(
        1,
        &local,
        "api",
        Some([10, 210, 1, 2]),
        vec![
            ingress("example.com", 80, HttpProtocol::Http),
            ingress("secure.example.com", 8443, HttpProtocol::Https),
        ],
    )];
    let certificates = BTreeMap::from([(
        IngressHost::parse("secure.example.com").unwrap(),
        CertificateRow::from_parts(CertificateMaterial::new("CERT", "KEY"), None),
    )]);

    let caddyfile = automatic_caddyfile(
        &local,
        "node-a",
        &service_containers(observations),
        "TIMESTAMP",
        None,
        &certificates,
    );

    let pin = pinned_tls_line(&caddyfile, "secure.example.com").expect("https pin");
    assert!(
        pin.contains("tls /config/certs/secure.example.com-")
            && pin.contains(".crt")
            && pin.contains(".key"),
        "{pin}"
    );
    assert!(caddyfile.contains(&format!(
        "https://secure.example.com {{\n\
{pin}\n\
\treverse_proxy 10.210.1.2:8443 {{\n\
\t\timport common_proxy\n\
\t}}\n\
\tlog\n\
}}\n"
    )));
    assert!(caddyfile.contains(
        "http://example.com {\n\
\treverse_proxy 10.210.1.2:80 {\n\
\t\timport common_proxy\n\
\t}\n\
\tlog\n\
}\n"
    ));
    assert!(!caddyfile.contains("tls /config/certs/example.com"));
}

